import { appendFileSync, copyFileSync, readFileSync, writeFileSync } from "node:fs";

const manifest = new URL(
  "../src-tauri/gen/android/app/src/main/AndroidManifest.xml",
  import.meta.url,
);
const source = readFileSync(manifest, "utf8");
const permissions = [
  ["uses-permission", "android.permission.CAMERA", ""],
  ["uses-feature", "android.hardware.camera", ' android:required="false"'],
  ["uses-feature", "android.hardware.camera.autofocus", ' android:required="false"'],
];

const missing = permissions
  .filter(([element, name]) => {
    const tags = source.match(new RegExp(`<${element}\\s+[^>]*>`, "g")) ?? [];
    return !tags.some((tag) => tag.includes(`"${name}"`) || tag.includes(`'${name}'`));
  })
  .map(([element, name, attributes]) => `    <${element} android:name="${name}"${attributes} />`);

if (missing.length) {
  const updated = source.replace(/<manifest\b[^>]*>/, (root) => {
    const newline = source.includes("\r\n") ? "\r\n" : "\n";
    return [root, ...missing].join(newline);
  });
  if (updated === source) throw new Error("Android manifest root element is missing");
  writeFileSync(manifest, updated);
}

const activity = new URL("./java/com/vmax/app/MainActivity.kt", manifest);
const decoder = new URL("./java/com/vmax/app/VmaxLowLatencyDecoder.kt", manifest);
const activitySource = readFileSync(activity, "utf8");
// Remove the startup hook from projects generated by earlier VmaX builds.
if (activitySource.includes("// VmaX native video")) {
  const updated = activitySource
    .replace(/^\s*\/\/ VmaX native video\s*\n\s*override fun onWebViewCreate\(webView: android\.webkit\.WebView\) \{\s*super\.onWebViewCreate\(webView\)\s*VmaxLowLatencyDecoder\.attach\(this, webView\)\s*\}\r?\n/gm, "\n")
    .replace(/^\s*\/\/ VmaX native video\s*\n\s*VmaxLowLatencyDecoder\.attach\(this, \w+\)\r?\n/gm, "\n");
  writeFileSync(activity, updated);
}
copyFileSync(new URL("./VmaxLowLatencyDecoder.kt", import.meta.url), decoder);

const proguard = new URL("../../proguard-rules.pro", manifest);
const decoderRule = `
# Rust resolves these static callbacks by their JVM names and descriptors.
-keep class com.vmax.app.VmaxLowLatencyDecoder {
    public static void onNativeVideoFrame(byte[], long, int, int, int, boolean);
    public static void layoutSurface(android.app.Activity, android.webkit.WebView, int, int, int, int, boolean);
    public static void resetSession();
}
`;
const existingRules = readFileSync(proguard, "utf8");
const priorRule = /\n# Rust resolves these static callbacks by their JVM names and descriptors\.\r?\n-keep class com\.vmax\.app\.VmaxLowLatencyDecoder \{[^}]*\}\r?\n/;
if (!existingRules.includes(decoderRule)) {
  const updated = existingRules.replace(priorRule, "");
  if (updated === existingRules) appendFileSync(proguard, decoderRule);
  else writeFileSync(proguard, updated + decoderRule);
}
