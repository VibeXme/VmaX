//! Android MediaCodec hand-off and hardware decode latency instrumentation.

use crate::jitter_buffer::{BufferedFrame, JitterConsumer, JitterProducer};
use crate::protocol::ReassembledFrame;
use jni::objects::{GlobalRef, JObject, JValue};
use jni::sys::{JNI_FALSE, jboolean, jint};
use jni::{JNIEnv, JavaVM};
use std::collections::VecDeque;
use std::sync::atomic::{AtomicBool, AtomicU32, AtomicU64, Ordering};
use std::sync::{Arc, Condvar, Mutex, MutexGuard, OnceLock};
use std::time::{Duration, Instant};

/// Fully-qualified JNI name of the Kotlin bridge class.
const DECODER_CLASS: &str = "com/vmax/app/VmaxLowLatencyDecoder";
/// Static facade generated by `@JvmStatic` in the Kotlin companion object.
const FRAME_CALLBACK: &str = "onNativeVideoFrame";
const FRAME_SIGNATURE: &str = "([BJIIIZ)V";
/// One pending access unit while the decoder processes the current frame.
const DECODER_QUEUE_CAPACITY: usize = 1;
/// Longest the decoder thread sleeps when the queue is empty; a push wakes it
/// immediately through the condvar, this is only a safety net.
const IDLE_WAIT: Duration = Duration::from_millis(8);
/// Never spin on a condvar timeout shorter than this.
const MIN_WAIT: Duration = Duration::from_micros(50);
/// A configured codec that produces no Surface output for this long, while
/// frames are actually being submitted, is treated as wedged.
const NATIVE_OUTPUT_DEADLINE: Duration = Duration::from_secs(2);
/// Require a few submitted frames before judging output; some devices take a
/// moment to emit the first buffer after `start()`.
const NATIVE_OUTPUT_MIN_FRAMES: u32 = 12;

/// Whether a Surface is attached and the native callbacks resolved.
static DECODER_ACTIVE: AtomicBool = AtomicBool::new(false);
static CODECS: AtomicU32 = AtomicU32::new(0);
/// Set when a fresh decoder needs a key frame before it can produce output.
static NEEDS_KEYFRAME: AtomicBool = AtomicBool::new(false);
/// Incremented by Kotlin for every decoded buffer released to the Surface.
static RENDERED_FRAMES: AtomicU64 = AtomicU64::new(0);
/// Set when a configured codec never produced output. Frames go back to the
/// WebView until the surface is reattached or the session restarts.
static FORCE_WEBVIEW: AtomicBool = AtomicBool::new(false);
/// Number of frames dropped because the Kotlin decoder could not keep up.
static BACKLOG_DROPS: AtomicU64 = AtomicU64::new(0);
/// Visible picture size reported by MediaCodec after output format negotiation.
static VIDEO_WIDTH: AtomicU32 = AtomicU32::new(0);
static VIDEO_HEIGHT: AtomicU32 = AtomicU32::new(0);
/// Whether the most recent access units were routed to MediaCodec.
static NATIVE_ROUTE: AtomicBool = AtomicBool::new(false);

static TARGET: Mutex<Option<Arc<DecoderTarget>>> = Mutex::new(None);
static QUEUE: OnceLock<Mutex<DecodeQueue>> = OnceLock::new();
static QUEUE_INIT: Mutex<()> = Mutex::new(());
/// FIFO of submission timestamps into MediaCodec so `nativeNotifyFrameRendered`
/// can compute exact wall-clock hardware decode latency (`Decode 5.50ms`).
static IN_FLIGHT_DECODES: Mutex<VecDeque<Instant>> = Mutex::new(VecDeque::new());

struct DecoderTarget {
    vm: Arc<JavaVM>,
    class: GlobalRef,
}

struct DecodeQueue {
    producer: JitterProducer,
    signal: Arc<(Mutex<u64>, Condvar)>,
    last_frame_id: Option<u32>,
    native_started: Option<Instant>,
    render_baseline: u64,
    queued_since_render: u32,
    backlog_since_render: u32,
}

impl DecodeQueue {
    fn reset_stream(&mut self) {
        self.producer.reset_stream();
        self.last_frame_id = None;
        self.reset_output_watchdog();
    }

    fn reset_output_watchdog(&mut self) {
        self.native_started = None;
        self.queued_since_render = 0;
        self.backlog_since_render = 0;
        self.render_baseline = RENDERED_FRAMES.load(Ordering::Acquire);
        lock(&IN_FLIGHT_DECODES).clear();
    }

    fn observe_output(&mut self, now: Instant, count_submission: bool) -> bool {
        let rendered = RENDERED_FRAMES.load(Ordering::Acquire);
        if rendered > self.render_baseline {
            self.render_baseline = rendered;
            self.native_started = Some(now);
            self.queued_since_render = 0;
            self.backlog_since_render = 0;
            return false;
        }
        let started = *self.native_started.get_or_insert(now);
        if count_submission {
            self.queued_since_render = self.queued_since_render.saturating_add(1);
        } else {
            self.backlog_since_render = self.backlog_since_render.saturating_add(1);
        }
        self.queued_since_render
            .saturating_add(self.backlog_since_render)
            >= NATIVE_OUTPUT_MIN_FRAMES
            && now.saturating_duration_since(started) >= NATIVE_OUTPUT_DEADLINE
    }
}

/// Routing decision returned to the client event loop.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FrameRoute {
    /// No native surface is attached; deliver through the WebView path.
    WebView,
    /// The frame was queued for MediaCodec.
    Native,
    /// The native queue is full and the frame was dropped.
    NativeBacklog,
}

/// True while Kotlin reports a live Surface and the callback is resolved.
pub fn is_active() -> bool {
    DECODER_ACTIVE.load(Ordering::Acquire)
}

pub fn supports(codec: crate::protocol::VideoCodec) -> bool {
    is_active()
        && !FORCE_WEBVIEW.load(Ordering::Acquire)
        && CODECS.load(Ordering::Acquire) & (1 << codec as u8) != 0
}

#[unsafe(no_mangle)]
pub extern "system" fn Java_com_vmax_app_VmaxLowLatencyDecoder_nativeSetDecoderCapabilities(
    _env: JNIEnv<'_>,
    _this: JObject<'_>,
    codecs: jint,
) {
    CODECS.store(codecs as u32, Ordering::Release);
}

/// Decoded buffers released to the Android Surface.
pub fn rendered_frames() -> u64 {
    RENDERED_FRAMES.load(Ordering::Acquire)
}

pub fn backlog_drops() -> u64 {
    BACKLOG_DROPS.load(Ordering::Relaxed)
}

/// Visible decoded picture size reported by MediaCodec, when known.
pub fn video_size() -> Option<(u32, u32)> {
    let width = VIDEO_WIDTH.load(Ordering::Relaxed);
    let height = VIDEO_HEIGHT.load(Ordering::Relaxed);
    (width > 0 && height > 0).then_some((width, height))
}

/// True while access units are being handed to MediaCodec.
pub fn native_route() -> bool {
    NATIVE_ROUTE.load(Ordering::Relaxed)
}

pub fn set_native_route(active: bool) {
    NATIVE_ROUTE.store(active, Ordering::Relaxed);
}

pub fn layout_surface(layout: crate::native_d3d11::SurfaceLayout) -> Result<(), String> {
    let Some(target) = lock(&TARGET).clone() else {
        return Ok(());
    };
    let mut env = target
        .vm
        .attach_current_thread()
        .map_err(|e| e.to_string())?;
    let picture = layout.picture;
    env.call_static_method(
        &target.class,
        "layoutSurface",
        "(IIIIZ)V",
        &[
            JValue::Int(picture.x),
            JValue::Int(picture.y),
            JValue::Int(picture.width),
            JValue::Int(picture.height),
            JValue::Bool(u8::from(layout.visible)),
        ],
    )
    .map(|_| ())
    .map_err(|e| e.to_string())
}

/// Clear session-scoped decoder state.
pub fn reset_route() {
    NATIVE_ROUTE.store(false, Ordering::Relaxed);
    VIDEO_WIDTH.store(0, Ordering::Relaxed);
    VIDEO_HEIGHT.store(0, Ordering::Relaxed);
    FORCE_WEBVIEW.store(false, Ordering::Release);
    if let Some(queue) = QUEUE.get() {
        lock(queue).reset_stream();
    }
    reset_surface_decoder();
}

/// Consume a pending key-frame request.
pub fn take_keyframe_request() -> bool {
    NEEDS_KEYFRAME.swap(false, Ordering::AcqRel)
}

/// Called from the QUIC receive path for every complete access unit.
pub fn submit_video_frame(frame: &ReassembledFrame) -> FrameRoute {
    if !crate::protocol::VideoCodec::from_u8(frame.codec).is_some_and(supports) {
        return FrameRoute::WebView;
    }
    let Some(queue) = QUEUE.get() else {
        return FrameRoute::WebView;
    };

    let mut queue = lock(queue);
    if queue
        .last_frame_id
        .is_some_and(|last| frame.frame_id < last)
    {
        queue.producer.reset_stream();
    }
    queue.last_frame_id = Some(frame.frame_id);

    let buffered = BufferedFrame {
        width: frame.meta.width,
        height: frame.meta.height,
        frame_id: frame.frame_id,
        timestamp_us: frame.timestamp_us,
        codec: frame.codec,
        is_keyframe: frame.is_keyframe,
        arrival: Instant::now(),
        payload: frame.payload.clone(),
    };

    let superseded = queue.producer.superseded_frames();
    if !queue.producer.push(buffered) {
        BACKLOG_DROPS.fetch_add(1, Ordering::Relaxed);
        let wedged = queue.observe_output(Instant::now(), false);
        drop(queue);
        if wedged {
            force_webview();
            return FrameRoute::WebView;
        }
        return FrameRoute::NativeBacklog;
    }

    if queue.producer.superseded_frames() != superseded {
        BACKLOG_DROPS.fetch_add(1, Ordering::Relaxed);
    }
    let wedged = queue.observe_output(Instant::now(), true);
    let signal = Arc::clone(&queue.signal);
    drop(queue);

    {
        let mut generation = lock(&signal.0);
        *generation = generation.wrapping_add(1);
    }
    signal.1.notify_one();

    if wedged {
        force_webview();
        return FrameRoute::WebView;
    }
    FrameRoute::Native
}

pub(crate) fn recover_stalled_decoder() {
    force_webview();
    if let Some(queue) = QUEUE.get() {
        lock(queue).reset_stream();
    }
}

fn force_webview() {
    NATIVE_ROUTE.store(false, Ordering::Relaxed);
    if !FORCE_WEBVIEW.swap(true, Ordering::AcqRel) {
        reset_surface_decoder();
        tracing::warn!(
            frames = NATIVE_OUTPUT_MIN_FRAMES,
            deadline_ms = NATIVE_OUTPUT_DEADLINE.as_millis() as u64,
            "MediaCodec produced no output; falling back to WebCodecs"
        );
    }
}

fn reset_surface_decoder() {
    let Some(target) = lock(&TARGET).clone() else {
        return;
    };
    if let Ok(mut env) = target.vm.attach_current_thread()
        && env
            .call_static_method(&target.class, "resetSession", "()V", &[])
            .is_err()
    {
        let _ = env.exception_clear();
    }
}

#[unsafe(no_mangle)]
pub extern "system" fn Java_com_vmax_app_VmaxLowLatencyDecoder_nativeSetDecoderActive(
    mut env: JNIEnv<'_>,
    _this: JObject<'_>,
    active: jboolean,
) {
    if active == JNI_FALSE {
        DECODER_ACTIVE.store(false, Ordering::Release);
        NATIVE_ROUTE.store(false, Ordering::Relaxed);
        lock(&IN_FLIGHT_DECODES).clear();
        return;
    }

    match register_target(&mut env).and_then(|target| {
        ensure_decoder_thread(&target)?;
        Ok(target)
    }) {
        Ok(target) => {
            *lock(&TARGET) = Some(target);
            if let Some(queue) = QUEUE.get() {
                lock(queue).reset_stream();
            }
            FORCE_WEBVIEW.store(false, Ordering::Release);
            DECODER_ACTIVE.store(true, Ordering::Release);
            NEEDS_KEYFRAME.store(true, Ordering::Release);
        }
        Err(err) => {
            DECODER_ACTIVE.store(false, Ordering::Release);
            tracing::warn!(error = %err, "Android decoder bridge unavailable");
        }
    }
}

#[unsafe(no_mangle)]
pub extern "system" fn Java_com_vmax_app_VmaxLowLatencyDecoder_nativeNotifyDecoderReset(
    _env: JNIEnv<'_>,
    _this: JObject<'_>,
) {
    if let Some(queue) = QUEUE.get() {
        let mut queue = lock(queue);
        queue.producer.reset_stream();
        queue.last_frame_id = None;
        // Keep the watchdog's progress across repeated MediaCodec resets.
        // A codec that repeatedly fails must still fall back to WebCodecs.
    }
    lock(&IN_FLIGHT_DECODES).clear();
    NEEDS_KEYFRAME.store(true, Ordering::Release);
}

#[unsafe(no_mangle)]
pub extern "system" fn Java_com_vmax_app_VmaxLowLatencyDecoder_nativeReportVideoSize(
    _env: JNIEnv<'_>,
    _this: JObject<'_>,
    width: jint,
    height: jint,
) {
    VIDEO_WIDTH.store(width.max(0) as u32, Ordering::Relaxed);
    VIDEO_HEIGHT.store(height.max(0) as u32, Ordering::Relaxed);
}

/// Called by Kotlin after `releaseOutputBuffer(index, true)` hands a decoded
/// buffer to the Surface. Measures exact wall-clock MediaCodec decode latency.
#[unsafe(no_mangle)]
pub extern "system" fn Java_com_vmax_app_VmaxLowLatencyDecoder_nativeNotifyFrameRendered(
    _env: JNIEnv<'_>,
    _this: JObject<'_>,
) {
    RENDERED_FRAMES.fetch_add(1, Ordering::Relaxed);
    if let Some(submitted_at) = lock(&IN_FLIGHT_DECODES).pop_front() {
        let decode_us = submitted_at.elapsed().as_micros() as u32;
        if (100..=250_000).contains(&decode_us) {
            crate::capture::record_decode_latency_us(decode_us);
        }
    }
}

/// Optional direct JNI hook if Kotlin measures `System.nanoTime()` around
/// `queueInputBuffer` -> `dequeueOutputBuffer` and reports microseconds directly.
#[unsafe(no_mangle)]
pub extern "system" fn Java_com_vmax_app_VmaxLowLatencyDecoder_nativeReportDecodeLatencyUs(
    _env: JNIEnv<'_>,
    _this: JObject<'_>,
    decode_us: jint,
) {
    if decode_us > 0 {
        crate::capture::record_decode_latency_us(decode_us as u32);
    }
}

fn register_target(env: &mut JNIEnv<'_>) -> Result<Arc<DecoderTarget>, String> {
    if let Some(existing) = lock(&TARGET).clone() {
        return Ok(existing);
    }

    let vm = env
        .get_java_vm()
        .map_err(|err| format!("GetJavaVM: {err}"))?;
    let class = env
        .find_class(DECODER_CLASS)
        .map_err(|err| format!("FindClass({DECODER_CLASS}): {err}"))?;
    env.get_static_method_id(&class, FRAME_CALLBACK, FRAME_SIGNATURE)
        .map_err(|err| {
            format!(
                "get_static_method_id({DECODER_CLASS}.{FRAME_CALLBACK}{FRAME_SIGNATURE}): {err}"
            )
        })?;
    let class = env
        .new_global_ref(&class)
        .map_err(|err| format!("NewGlobalRef({DECODER_CLASS}): {err}"))?;

    Ok(Arc::new(DecoderTarget {
        vm: Arc::new(vm),
        class,
    }))
}

fn ensure_decoder_thread(target: &Arc<DecoderTarget>) -> Result<(), String> {
    if QUEUE.get().is_some() {
        return Ok(());
    }
    let _init = lock(&QUEUE_INIT);
    if QUEUE.get().is_some() {
        return Ok(());
    }

    let signal = Arc::new((Mutex::new(0u64), Condvar::new()));
    let (producer, consumer) = JitterProducer::new(Instant::now(), DECODER_QUEUE_CAPACITY);

    let thread_target = Arc::clone(target);
    let thread_signal = Arc::clone(&signal);
    std::thread::Builder::new()
        .name("vmax-mediacodec".to_string())
        .spawn(move || decoder_thread(thread_target, consumer, thread_signal))
        .map_err(|err| format!("spawn vmax-mediacodec: {err}"))?;

    let _ = QUEUE.set(Mutex::new(DecodeQueue {
        producer,
        signal,
        last_frame_id: None,
        native_started: None,
        render_baseline: RENDERED_FRAMES.load(Ordering::Acquire),
        queued_since_render: 0,
        backlog_since_render: 0,
    }));
    Ok(())
}

fn decoder_thread(
    target: Arc<DecoderTarget>,
    mut consumer: JitterConsumer,
    signal: Arc<(Mutex<u64>, Condvar)>,
) {
    let mut env = match target.vm.attach_current_thread_as_daemon() {
        Ok(env) => env,
        Err(err) => {
            tracing::warn!(error = %err, "could not attach decoder thread to the JVM");
            return;
        }
    };

    let mut generation = 0u64;
    let mut failures = 0u64;

    loop {
        if !is_active() || FORCE_WEBVIEW.load(Ordering::Acquire) {
            consumer.reset();
            generation = wait_for_frame(&signal, generation, Duration::from_millis(20));
            continue;
        }

        let now = Instant::now();
        if let Some(frame) = consumer.next(now) {
            if let Err(err) = deliver_frame(&mut env, &target.class, &frame) {
                consumer.decoder_rejected_frame();
                if consumer.take_keyframe_request() {
                    NEEDS_KEYFRAME.store(true, Ordering::Release);
                }
                failures += 1;
                if failures == 1 || failures % 240 == 0 {
                    tracing::warn!(
                        error = %err,
                        failures,
                        frame_id = frame.frame_id,
                        bytes = frame.payload.len(),
                        "MediaCodec frame delivery failed"
                    );
                }
                if env.exception_check().unwrap_or(false) {
                    let _ = env.exception_describe();
                    let _ = env.exception_clear();
                }
            }
            continue;
        }

        if consumer.take_keyframe_request() {
            NEEDS_KEYFRAME.store(true, Ordering::Release);
        }
        let timeout = consumer
            .pending_due()
            .map(|due| due.saturating_duration_since(Instant::now()))
            .unwrap_or(IDLE_WAIT)
            .clamp(MIN_WAIT, IDLE_WAIT);
        generation = wait_for_frame(&signal, generation, timeout);
    }
}

fn wait_for_frame(signal: &(Mutex<u64>, Condvar), observed: u64, timeout: Duration) -> u64 {
    let generation = lock(&signal.0);
    if *generation != observed {
        return *generation;
    }
    let (generation, _) = signal
        .1
        .wait_timeout(generation, timeout)
        .unwrap_or_else(|poisoned| poisoned.into_inner());
    *generation
}

fn deliver_frame(
    env: &mut JNIEnv<'_>,
    class: &GlobalRef,
    frame: &BufferedFrame,
) -> Result<(), jni::errors::Error> {
    {
        let mut inflight = lock(&IN_FLIGHT_DECODES);
        if inflight.len() >= 32 {
            inflight.pop_front();
        }
        inflight.push_back(Instant::now());
    }
    let bytes = env.byte_array_from_slice(&frame.payload)?;
    let timestamp_us = frame.timestamp_us.min(i64::MAX as u64) as i64;
    let result = env.call_static_method(
        class,
        FRAME_CALLBACK,
        FRAME_SIGNATURE,
        &[
            JValue::Object(&bytes),
            JValue::Long(timestamp_us),
            JValue::Int(i32::from(frame.codec)),
            JValue::Int(i32::from(frame.width)),
            JValue::Int(i32::from(frame.height)),
            JValue::Bool(u8::from(frame.is_keyframe)),
        ],
    );
    let _ = env.delete_local_ref(bytes);
    result.map(|_| ())
}

fn lock<T>(mutex: &Mutex<T>) -> MutexGuard<'_, T> {
    mutex
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner())
}
