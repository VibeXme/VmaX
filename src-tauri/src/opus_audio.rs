//! Opus audio codec support with Packet Loss Concealment (PLC).
//!
//! This module replaces raw PCM transmission with Opus at 48 kHz stereo.
//! The client decoder enables PLC to smoothly interpolate missing packets
//! and prevent audio clipping during network jitter.

use bytes::Bytes;
use cpal::traits::{DeviceTrait, HostTrait, StreamTrait};
use cpal::{SampleFormat, Stream, StreamConfig};
use core::num::NonZeroU32;
use opus1::{Application, Bitrate, Channels, InbandFec, OpusDecoder, OpusEncoder, SampleRate, Signal};
use std::collections::VecDeque;
use std::sync::atomic::{AtomicBool, AtomicU32, Ordering};
use std::sync::{Arc, Mutex};
use std::time::{SystemTime, UNIX_EPOCH};
use tokio::sync::mpsc;
use tracing::{debug, info, warn};

use crate::protocol::{AudioCodec, AudioPacket, AudioPacketHeader, audio_flags};

const OPUS_SAMPLE_RATE: SampleRate = SampleRate::Hz48000;
const OPUS_FRAME_SIZE: usize = 960; // 20 ms @ 48 kHz
const OPUS_CHANNELS: usize = 2;
const OPUS_BITRATE_BPS: i32 = 128_000; // 128 kbps stereo
const PLAYBACK_PREFILL_MS: usize = 30;
const PLAYBACK_MAX_BUFFER_MS: usize = 95;

/// Opus audio packet flags
pub mod opus_audio_flags {
    pub const PLC: u8 = 1 << 0; // Packet was concealed (generated by PLC)
}

/// Create an Opus audio packet from encoded payload
pub fn make_opus_audio_packet(
    seq: u32,
    timestamp_us: u64,
    payload: Bytes,
    flags: u8,
) -> AudioPacket {
    AudioPacket {
        header: AudioPacketHeader {
            codec: AudioCodec::Opus as u8,
            flags: flags | audio_flags::DENOISED,
            channels: OPUS_CHANNELS as u8,
            seq,
            timestamp_us,
        },
        payload,
    }
}

/// Playback buffer with Opus PLC support
struct OpusPlaybackBuffer {
    decoder: OpusDecoder,
    samples: VecDeque<f32>,
    last_seq: Option<u32>,
    pending: Vec<(u32, Bytes)>,
    max_samples: usize,
    callback_len: usize,
    playing: bool,
    phase: f64,
    rate: f64,
    last_frame: [f32; 8],
    channels: usize,
    plc_frames_concealed: u32,
}

impl OpusPlaybackBuffer {
    fn new() -> Result<Self, String> {
        let decoder = OpusDecoder::new(OPUS_SAMPLE_RATE, Channels::Stereo)
            .map_err(|e| format!("Failed to create Opus decoder: {e}"))?;
        Ok(Self {
            decoder,
            samples: VecDeque::with_capacity(16_384),
            last_seq: None,
            pending: Vec::with_capacity(16),
            max_samples: 0,
            callback_len: 0,
            playing: false,
            phase: 0.0,
            rate: 1.0,
            last_frame: [0.0; 8],
            channels: 2,
            plc_frames_concealed: 0,
        })
    }

    /// Push an Opus packet for decoding and playback
    fn push(&mut self, seq: u32, payload: &[u8], max_samples: usize) {
        if payload.is_empty() {
            return;
        }
        self.max_samples = max_samples;

        if let Some(previous) = self.last_seq {
            let distance = seq.wrapping_sub(previous);
            if distance == 0 || distance >= 1 << 31 {
                return;
            }
            // Only reset on major stall (> ~90ms at 20ms/pkt), not brief Wi-Fi jitter
            if distance > 5 {
                self.samples.clear();
                self.pending.clear();
                self.playing = false;
                self.phase = 0.0;
                self.rate = 1.0;
            } else if distance > 1 {
                if !self.pending.iter().any(|(id, _)| *id == seq) {
                    self.pending.push((seq, Bytes::copy_from_slice(payload)));
                }
                return;
            }
        }
        self.decode_and_append(seq, payload);
        self.drain_pending(0);
    }

    /// Decode Opus packet and append to buffer, using PLC for missing packets
    fn decode_and_append(&mut self, seq: u32, payload: &[u8]) {
        self.last_seq = Some(seq);
        let mut pcm = vec![0.0f32; OPUS_FRAME_SIZE * OPUS_CHANNELS];
        
        // Try to decode the packet
        match self.decoder.decode(payload, OPUS_FRAME_SIZE, &mut pcm) {
            Ok(decoded_samples) => {
                // Successful decode
                let limit = self
                    .max_samples
                    .max(self.callback_len.saturating_add(self.max_samples / 2));
                self.samples.extend(&pcm[..decoded_samples]);
                let excess = self.samples.len().saturating_sub(limit);
                if excess > 0 {
                    self.samples.drain(..excess);
                    self.phase = 0.0;
                }
                self.plc_frames_concealed = 0;
            }
            Err(_) => {
                // Decode failed - use PLC to generate concealment frame
                self.conceal_frame(&mut pcm);
                self.plc_frames_concealed += 1;
                
                let limit = self
                    .max_samples
                    .max(self.callback_len.saturating_add(self.max_samples / 2));
                self.samples.extend(&pcm[..OPUS_FRAME_SIZE * OPUS_CHANNELS]);
                let excess = self.samples.len().saturating_sub(limit);
                if excess > 0 {
                    self.samples.drain(..excess);
                    self.phase = 0.0;
                }
            }
        }
    }

    /// Generate a concealment frame using Opus PLC
    fn conceal_frame(&mut self, output: &mut [f32]) {
        // Opus PLC: pass empty slice to generate concealment
        let _ = self.decoder.decode(&[], OPUS_FRAME_SIZE, output);
    }

    /// Bridge a short loss from the last emitted sample into the next packet
    fn conceal_gap(&mut self, missing_packets: usize, next_payload: &[u8]) {
        let mut next_pcm = vec![0.0f32; OPUS_FRAME_SIZE * OPUS_CHANNELS];
        let _ = self.decoder.decode(next_payload, OPUS_FRAME_SIZE, &mut next_pcm);
        let frame_count = OPUS_FRAME_SIZE;

        for packet_index in 0..missing_packets {
            let blend = (packet_index + 1) as f32 / (missing_packets + 1) as f32;
            for frame in 0..frame_count {
                let frame_blend = blend * (frame + 1) as f32 / frame_count as f32;
                for channel in 0..self.channels {
                    let from = self.last_frame.get(channel).copied().unwrap_or(0.0);
                    let to = next_pcm[frame * self.channels + channel];
                    self.samples.push_back(from + (to - from) * frame_blend);
                }
            }
        }
    }

    fn drain_pending(&mut self, needed: usize) {
        while let Some(previous) = self.last_seq {
            let Some((index, distance)) = self
                .pending
                .iter()
                .enumerate()
                .map(|(index, (seq, _))| (index, seq.wrapping_sub(previous)))
                .min_by_key(|(_, distance)| *distance)
            else {
                break;
            };
            if distance > 1 && self.samples.len() >= needed {
                break;
            }
            let (seq, payload) = self.pending.swap_remove(index);
            if distance > 1 {
                debug!(
                    missing = distance - 1,
                    previous, seq, "Opus audio packets missed playout deadline, using PLC"
                );
                self.conceal_gap((distance as usize - 1).min(4), &payload);
            }
            self.decode_and_append(seq, &payload);
        }
    }

    fn render<T: cpal::Sample + cpal::FromSample<f32>>(
        &mut self,
        out: &mut [T],
        prefill: usize,
        channels: usize,
    ) {
        self.callback_len = out.len();
        self.channels = channels;
        let needed = if self.playing {
            out.len()
        } else {
            out.len().saturating_add(prefill)
        };
        self.drain_pending(needed);
        if !self.playing {
            self.playing = self.samples.len() >= out.len().saturating_add(prefill);
        }
        if !self.playing {
            // Smoothly fade held samples to silence instead of hard-cutting to zero
            for frame in out.chunks_exact_mut(channels) {
                for (ch, slot) in frame.iter_mut().enumerate() {
                    let held = if ch < self.last_frame.len() {
                        self.last_frame[ch] *= 0.96;
                        self.last_frame[ch]
                    } else {
                        0.0
                    };
                    *slot = T::from_sample(held);
                }
            }
            self.phase = 0.0;
            self.rate = 1.0;
            return;
        }

        let target = out.len() + prefill;
        let error = (self.samples.len() as f64 - target as f64) / target.max(1) as f64;
        let desired_rate = 1.0 + (error * 0.008).clamp(-0.005, 0.005);
        self.rate += (desired_rate - self.rate) * 0.02;

        for frame in out.chunks_exact_mut(channels) {
            if self.samples.len() < channels {
                // Buffer briefly ran dry mid-callback: decay smoothly without resetting `playing`
                for (ch, slot) in frame.iter_mut().enumerate() {
                    let held = if ch < self.last_frame.len() {
                        self.last_frame[ch] *= 0.92;
                        self.last_frame[ch]
                    } else {
                        0.0
                    };
                    *slot = T::from_sample(held);
                }
                continue;
            }

            for (channel, slot) in frame.iter_mut().enumerate() {
                let a = self.samples.get(channel).copied().unwrap_or(0.0);
                let b = self.samples.get(channels + channel).copied().unwrap_or(a);
                let sample = a + (b - a) * self.phase as f32;
                if channel < self.last_frame.len() {
                    self.last_frame[channel] = sample;
                }
                *slot = T::from_sample(sample);
            }
            self.phase += self.rate;
            let consumed = self.phase as usize;
            self.phase -= consumed as f64;
            let drain_count = (consumed * channels).min(self.samples.len());
            self.samples.drain(..drain_count);
        }

        if self.samples.is_empty() {
            self.playing = false;
        }
    }
}

/// Opus audio capture handle for host
pub struct OpusAudioCaptureHandle {
    stop_flag: Arc<AtomicBool>,
    thread: Option<std::thread::JoinHandle<()>>,
}

impl OpusAudioCaptureHandle {
    pub fn stop(mut self) {
        self.stop_flag.store(true, Ordering::Relaxed);
        if let Some(handle) = self.thread.take() {
            let _ = handle.join();
        }
    }
}

impl Drop for OpusAudioCaptureHandle {
    fn drop(&mut self) {
        self.stop_flag.store(true, Ordering::Relaxed);
        if let Some(handle) = self.thread.take() {
            let _ = handle.join();
        }
    }
}

/// Opus audio playback handle for client
pub struct OpusAudioPlaybackHandle {
    stop_flag: Arc<AtomicBool>,
    ring: Arc<Mutex<OpusPlaybackBuffer>>,
    thread: Option<std::thread::JoinHandle<()>>,
    target_rate: u32,
    target_channels: u16,
}

impl OpusAudioPlaybackHandle {
    pub fn push_packet(&self, pkt: &AudioPacket) {
        if pkt.payload.is_empty() {
            return;
        }

        let channels = (pkt.header.channels as usize).max(1);
        let target_ch = self.target_channels.max(1) as usize;
        if !matches!(channels, 1 | 2) {
            return;
        }

        let Ok(mut guard) = self.ring.lock() else {
            return;
        };
        let configured =
            (self.target_rate as usize * PLAYBACK_MAX_BUFFER_MS / 1_000).max(1) * target_ch;
        guard.push(pkt.header.seq, &pkt.payload, configured);
    }

    pub fn plc_frames_concealed(&self) -> u32 {
        if let Ok(guard) = self.ring.lock() {
            guard.plc_frames_concealed
        } else {
            0
        }
    }

    pub fn stop(mut self) {
        self.stop_flag.store(true, Ordering::Relaxed);
        if let Some(handle) = self.thread.take() {
            let _ = handle.join();
        }
    }
}

impl Drop for OpusAudioPlaybackHandle {
    fn drop(&mut self) {
        self.stop_flag.store(true, Ordering::Relaxed);
        if let Some(handle) = self.thread.take() {
            let _ = handle.join();
        }
    }
}

fn now_unix_us() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_micros() as u64
}

/// Start host audio capture with Opus encoding
pub fn start_host_opus_audio_capture(
    audio_tx: mpsc::Sender<AudioPacket>,
    bitrate_kbps: u32,
    output_id: Option<String>,
    process_id: Option<u32>,
    exclude_discord: bool,
) -> Result<OpusAudioCaptureHandle, String> {
    let stop_flag = Arc::new(AtomicBool::new(false));
    let stop_worker = Arc::clone(&stop_flag);

    let (init_tx, init_rx) = std::sync::mpsc::channel::<Result<(), String>>();

    let thread = std::thread::Builder::new()
        .name("vmax-opus-audio-capture".to_string())
        .spawn(move || {
            #[cfg(target_os = "windows")]
            if exclude_discord || process_id.is_some() || output_id.is_none() {
                let target = if let Some(pid) = process_id {
                    (pid, true)
                } else if exclude_discord {
                    (discord_root_pid().unwrap_or_else(|_| std::process::id()), false)
                } else {
                    (std::process::id(), false)
                };
                if let Err(err) = capture_process_opus_audio(target.0, target.1, &audio_tx, &stop_worker, &init_tx, bitrate_kbps) {
                    warn!(%err, "filtered Opus audio capture stopped");
                    let _ = init_tx.send(Err(err));
                }
                return;
            }
            #[cfg(not(target_os = "windows"))]
            let _ = (process_id, exclude_discord);

            let host = cpal::default_host();
            let mut candidates: Vec<(cpal::Device, cpal::SupportedStreamConfig, bool)> = Vec::new();
            let device = match output_id.as_deref() {
                Some(id) => host.output_devices().ok().and_then(|mut outputs| {
                    outputs.find(|device| device.id().is_ok_and(|candidate| candidate.to_string() == id))
                }),
                None => host.default_output_device(),
            };
            if let Some(out_dev) = device
                && let Ok(cfg) = out_dev.default_output_config()
            {
                candidates.push((out_dev, cfg, true));
            }
            if candidates.is_empty() {
                let _ = init_tx.send(Err(
                    "The selected playback device is unavailable. Choose another host audio output.".to_string(),
                ));
                return;
            }

            let mut opened: Option<(Stream, u32, usize, bool)> = None;
            let mut last_err = String::from("unable to open audio capture device");

            for (device, config, is_loopback) in candidates {
                let src_rate = config.sample_rate();
                let src_channels = config.channels() as usize;
                let sample_format = config.sample_format();
                let stream_cfg: StreamConfig = config.into();
                let seq_counter = Arc::new(AtomicU32::new(1));
                let processor = Arc::new(Mutex::new(OpusHostAudioProcessor::new(
                    src_rate,
                    src_channels,
                    is_loopback,
                    bitrate_kbps,
                )));

                let tx_cb = audio_tx.clone();
                let seq_cb = Arc::clone(&seq_counter);
                let proc_cb = Arc::clone(&processor);
                let err_cb = |err: cpal::Error| {
                    warn!(error = %err, "host Opus audio capture stream error");
                };

                let build_res: Result<Stream, String> = match sample_format {
                    SampleFormat::F32 => device
                        .build_input_stream(
                            stream_cfg,
                            move |data: &[f32], _| {
                                if let Ok(mut guard) = proc_cb.lock() {
                                    guard.push_and_emit(data, &seq_cb, &tx_cb);
                                }
                            },
                            err_cb,
                            None,
                        )
                        .map_err(|e| format!("failed to build f32 capture stream: {e}")),
                    SampleFormat::I16 => device
                        .build_input_stream(
                            stream_cfg,
                            move |data: &[i16], _| {
                                let converted: Vec<f32> =
                                    data.iter().map(|&s| s as f32 / 32768.0).collect();
                                if let Ok(mut guard) = proc_cb.lock() {
                                    guard.push_and_emit(&converted, &seq_cb, &tx_cb);
                                }
                            },
                            err_cb,
                            None,
                        )
                        .map_err(|e| format!("failed to build i16 capture stream: {e}")),
                    SampleFormat::U16 => device
                        .build_input_stream(
                            stream_cfg,
                            move |data: &[u16], _| {
                                let converted: Vec<f32> = data
                                    .iter()
                                    .map(|&s| (s as f32 - 32768.0) / 32768.0)
                                    .collect();
                                if let Ok(mut guard) = proc_cb.lock() {
                                    guard.push_and_emit(&converted, &seq_cb, &tx_cb);
                                }
                            },
                            err_cb,
                            None,
                        )
                        .map_err(|e| format!("failed to build u16 capture stream: {e}")),
                    other => Err(format!("unsupported host audio sample format: {other:?}")),
                };

                match build_res {
                    Ok(s) => {
                        opened = Some((s, src_rate, src_channels, is_loopback));
                        break;
                    }
                    Err(e) => {
                        last_err = e;
                    }
                }
            }

            let Some((stream, _src_rate, _src_channels, _source_is_loopback)) = opened else {
                let _ = init_tx.send(Err(last_err));
                return;
            };

            if let Err(e) = stream.play() {
                let _ = init_tx.send(Err(format!("failed to start audio capture stream: {e}")));
                return;
            }

            info!("host Opus audio capture active @ 48kHz stereo");
            let _ = init_tx.send(Ok(()));

            while !stop_worker.load(Ordering::Relaxed) {
                std::thread::sleep(std::time::Duration::from_millis(25));
            }
            drop(stream);
        })
        .map_err(|e| format!("failed to spawn Opus audio capture thread: {e}"))?;

    match init_rx.recv() {
        Ok(Ok(())) => Ok(OpusAudioCaptureHandle {
            stop_flag,
            thread: Some(thread),
        }),
        Ok(Err(e)) => {
            stop_flag.store(true, Ordering::Relaxed);
            let _ = thread.join();
            Err(e)
        }
        Err(_) => {
            stop_flag.store(true, Ordering::Relaxed);
            let _ = thread.join();
            Err("audio capture thread exited unexpectedly".to_string())
        }
    }
}

/// Start client audio playback with Opus decoding and PLC
pub fn start_client_opus_audio_playback() -> Result<OpusAudioPlaybackHandle, String> {
    let stop_flag = Arc::new(AtomicBool::new(false));
    let ring = Arc::new(Mutex::new(OpusPlaybackBuffer::new()?));
    let stop_worker = Arc::clone(&stop_flag);
    let ring_worker = Arc::clone(&ring);

    let (init_tx, init_rx) = std::sync::mpsc::channel::<Result<(u32, u16), String>>();

    let thread = std::thread::Builder::new()
        .name("vmax-opus-audio-playback".to_string())
        .spawn(move || {
            let host = cpal::default_host();
            let Some(device) = host.default_output_device() else {
                let _ = init_tx.send(Err("no audio output device found".to_string()));
                return;
            };
            let cfg = match device.default_output_config() {
                Ok(c) => c,
                Err(e) => {
                    let _ = init_tx.send(Err(format!("default output config failed: {e}")));
                    return;
                }
            };

            let target_rate = cfg.sample_rate();
            let target_channels = cfg.channels();
            let sample_format = cfg.sample_format();
            let stream_cfg: StreamConfig = cfg.into();
            let prefill =
                (target_rate as usize * PLAYBACK_PREFILL_MS / 1_000) * usize::from(target_channels);

            let err_cb = |err: cpal::Error| {
                debug!(error = %err, "client Opus audio playback stream error");
            };

            macro_rules! output_stream {
                ($sample:ty) => {
                    device
                        .build_output_stream(
                            stream_cfg,
                            move |out: &mut [$sample], _| {
                                if let Ok(mut guard) = ring_worker.lock() {
                                    guard.render(out, prefill, usize::from(target_channels));
                                } else {
                                    out.fill(<$sample as cpal::Sample>::EQUILIBRIUM);
                                }
                            },
                            err_cb,
                            None,
                        )
                        .map_err(|e| format!("failed to open {sample_format:?} audio output: {e}"))
                };
            }
            let build_res: Result<Stream, String> = match sample_format {
                SampleFormat::F32 => output_stream!(f32),
                SampleFormat::I16 => output_stream!(i16),
                SampleFormat::U16 => output_stream!(u16),
                SampleFormat::I32 => output_stream!(i32),
                other => Err(format!("unsupported playback sample format: {other:?}")),
            };

            let stream = match build_res {
                Ok(s) => s,
                Err(e) => {
                    let _ = init_tx.send(Err(e));
                    return;
                }
            };

            if let Err(e) = stream.play() {
                let _ = init_tx.send(Err(format!("failed to start audio playback: {e}")));
                return;
            }

            let _ = init_tx.send(Ok((target_rate, target_channels)));

            while !stop_worker.load(Ordering::Relaxed) {
                std::thread::sleep(std::time::Duration::from_millis(25));
            }
            drop(stream);
        })
        .map_err(|e| format!("failed to spawn Opus audio playback thread: {e}"))?;

    match init_rx.recv() {
        Ok(Ok((target_rate, target_channels))) => Ok(OpusAudioPlaybackHandle {
            stop_flag,
            ring,
            thread: Some(thread),
            target_rate,
            target_channels,
        }),
        Ok(Err(e)) => {
            stop_flag.store(true, Ordering::Relaxed);
            let _ = thread.join();
            Err(e)
        }
        Err(_) => {
            stop_flag.store(true, Ordering::Relaxed);
            let _ = thread.join();
            Err("audio playback thread exited unexpectedly".to_string())
        }
    }
}

struct OpusHostAudioProcessor {
    src_rate: u32,
    src_channels: usize,
    source_is_loopback: bool,
    encoder: OpusEncoder,
    channel_queues: Vec<VecDeque<f32>>,
    in_scratch: Vec<f32>,
}

impl OpusHostAudioProcessor {
    fn new(src_rate: u32, src_channels: usize, source_is_loopback: bool, bitrate_kbps: u32) -> Self {
        let mut encoder = OpusEncoder::new(OPUS_SAMPLE_RATE, Channels::Stereo, Application::Audio)
            .expect("Failed to create Opus encoder");
        encoder.set_bitrate(Bitrate::BitsPerSecond(NonZeroU32::new((bitrate_kbps * 1000) as u32).unwrap()));
        encoder.set_signal(Signal::Auto);
        let _ = encoder.set_complexity(5);
        encoder.set_inband_fec(InbandFec::On);
        let _ = encoder.set_packet_loss_perc(5);

        let ch = 2;
        Self {
            src_rate,
            src_channels: src_channels.max(1),
            source_is_loopback,
            encoder,
            channel_queues: (0..ch).map(|_| VecDeque::with_capacity(4096)).collect(),
            in_scratch: vec![0.0; OPUS_FRAME_SIZE],
        }
    }

    fn push_and_emit(
        &mut self,
        interleaved: &[f32],
        seq_counter: &AtomicU32,
        audio_tx: &mpsc::Sender<AudioPacket>,
    ) {
        let remixed = remix_channels(interleaved, self.src_channels, 2);
        let at_48k = resample_cubic_interleaved(
            &remixed,
            self.src_rate,
            OPUS_SAMPLE_RATE as u32,
            2,
        );
        let frames = at_48k.len() / 2;
        for f in 0..frames {
            for ch in 0..2 {
                self.channel_queues[ch].push_back(at_48k[f * 2 + ch]);
            }
        }

        while self.channel_queues.iter().all(|q| q.len() >= OPUS_FRAME_SIZE) {
            for ch in 0..2 {
                for sample_slot in &mut self.in_scratch[..OPUS_FRAME_SIZE] {
                    let s = self.channel_queues[ch].pop_front().unwrap_or(0.0);
                    *sample_slot = s.clamp(-1.0, 1.0);
                }
            }

            // Interleave for Opus encoder
            let mut interleaved_pcm = vec![0.0f32; OPUS_FRAME_SIZE * 2];
            for i in 0..OPUS_FRAME_SIZE {
                interleaved_pcm[i * 2] = self.in_scratch[i];
                interleaved_pcm[i * 2 + 1] = self.channel_queues[1][i];
            }

            // Encode to Opus
            let mut opus_data = vec![0u8; 4000];
            match self.encoder.encode(&interleaved_pcm, OPUS_FRAME_SIZE, &mut opus_data) {
                Ok(bytes_written) => {
                    opus_data.truncate(bytes_written);
                    let seq = seq_counter.fetch_add(1, Ordering::Relaxed);
                    let pkt = AudioPacket {
                        header: AudioPacketHeader {
                            codec: AudioCodec::Opus as u8,
                            flags: if self.source_is_loopback { 0 } else { audio_flags::VOICE_TRACK },
                            channels: 2,
                            seq,
                            timestamp_us: now_unix_us(),
                        },
                        payload: Bytes::from(opus_data),
                    };
                    let _ = audio_tx.try_send(pkt);
                }
                Err(e) => {
                    warn!(%e, "Opus encoding failed");
                }
            }
        }
    }
}

fn remix_channels(input: &[f32], src_ch: usize, dst_ch: usize) -> Vec<f32> {
    if src_ch == dst_ch {
        return input.to_vec();
    }
    let frames = input.len() / src_ch.max(1);
    let mut out = Vec::with_capacity(frames * dst_ch);
    for f in 0..frames {
        let base = f * src_ch;
        if dst_ch == 1 {
            let sum: f32 = input[base..base + src_ch].iter().copied().sum();
            out.push(sum / src_ch as f32);
        } else {
            let mono_or_l = input[base];
            let r = if src_ch > 1 {
                input[base + 1]
            } else {
                mono_or_l
            };
            for c in 0..dst_ch {
                out.push(if c % 2 == 0 { mono_or_l } else { r });
            }
        }
    }
    out
}

/// 4-point Catmull-Rom cubic interpolator for sample rate conversion
fn resample_cubic_interleaved(
    input: &[f32],
    src_rate: u32,
    dst_rate: u32,
    channels: usize,
) -> Vec<f32> {
    if src_rate == dst_rate || input.is_empty() || channels == 0 {
        return input.to_vec();
    }
    let src_frames = input.len() / channels;
    if src_frames < 4 {
        return input.to_vec();
    }
    let dst_frames = ((src_frames as f64) * (dst_rate as f64 / src_rate as f64))
        .round()
        .max(1.0) as usize;
    let mut out = Vec::with_capacity(dst_frames * channels);
    let ratio = (src_frames - 1) as f64 / (dst_frames.saturating_sub(1).max(1)) as f64;

    for i in 0..dst_frames {
        let pos = (i as f64) * ratio;
        let idx = (pos.floor() as usize).min(src_frames - 2);
        let t = (pos - idx as f64) as f32;
        let t2 = t * t;
        let t3 = t2 * t;

        let i0 = idx.saturating_sub(1);
        let i1 = idx;
        let i2 = (idx + 1).min(src_frames - 1);
        let i3 = (idx + 2).min(src_frames - 1);

        for ch in 0..channels {
            let p0 = input[i0 * channels + ch];
            let p1 = input[i1 * channels + ch];
            let p2 = input[i2 * channels + ch];
            let p3 = input[i3 * channels + ch];

            let sample = 0.5
                * ((2.0 * p1)
                    + (-p0 + p2) * t
                    + (2.0 * p0 - 5.0 * p1 + 4.0 * p2 - p3) * t2
                    + (-p0 + 3.0 * p1 - 3.0 * p2 + p3) * t3);
            out.push(sample.clamp(-1.0, 1.0));
        }
    }
    out
}

#[cfg(target_os = "windows")]
fn discord_root_pid() -> Result<u32, String> {
    use windows::Win32::Foundation::CloseHandle;
    use windows::Win32::System::Diagnostics::ToolHelp::{
        CreateToolhelp32Snapshot, PROCESSENTRY32W, Process32FirstW, Process32NextW,
        TH32CS_SNAPPROCESS,
    };
    let snapshot = unsafe { CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0) }
        .map_err(|err| err.to_string())?;
    let mut entry = PROCESSENTRY32W {
        dwSize: std::mem::size_of::<PROCESSENTRY32W>() as u32,
        ..Default::default()
    };
    let mut discord = Vec::new();
    let mut next = unsafe { Process32FirstW(snapshot, &mut entry) };
    while next.is_ok() {
        let len = entry
            .szExeFile
            .iter()
            .position(|&ch| ch == 0)
            .unwrap_or(entry.szExeFile.len());
        let name = String::from_utf16_lossy(&entry.szExeFile[..len]).to_ascii_lowercase();
        if matches!(
            name.as_str(),
            "discord.exe" | "discordptb.exe" | "discordcanary.exe" | "discorddevelopment.exe"
        ) {
            discord.push((entry.th32ProcessID, entry.th32ParentProcessID));
        }
        next = unsafe { Process32NextW(snapshot, &mut entry) };
    }
    let _ = unsafe { CloseHandle(snapshot) };
    let mut roots = discord
        .iter()
        .filter(|(_, parent)| !discord.iter().any(|(pid, _)| pid == parent));
    match (roots.next(), roots.next()) {
        (Some(&(pid, _)), None) => Ok(pid),
        (None, _) => Err("Open the Discord desktop app before hosting with Discord exclusion.".into()),
        _ => Err(
            "Close extra Discord desktop instances before hosting with Discord exclusion.".into(),
        ),
    }
}

#[cfg(target_os = "windows")]
fn capture_process_opus_audio(
    pid: u32,
    include: bool,
    tx: &mpsc::Sender<AudioPacket>,
    stop: &AtomicBool,
    ready: &std::sync::mpsc::Sender<Result<(), String>>,
    bitrate_kbps: u32,
) -> Result<(), String> {
    use wasapi::{AudioClient, Direction, SampleType, StreamMode, WaveFormat};

    wasapi::initialize_mta()
        .ok()
        .map_err(|err| err.to_string())?;
    let result = (|| -> Result<(), wasapi::WasapiError> {
        let mut client = AudioClient::new_application_loopback_client(pid, include)?;
        let format = WaveFormat::new(
            32,
            32,
            SampleType::Float,
            OPUS_SAMPLE_RATE as usize,
            2,
            None,
        );
        let mode = StreamMode::EventsShared {
            autoconvert: true,
            buffer_duration_hns: 0,
        };
        client.initialize_client(&format, Direction::Capture, mode, None)?;
        let event = client.set_get_eventhandle()?;
        let capture = client.get_audiocaptureclient()?;
        let mut bytes = VecDeque::new();
        let mut processor = OpusHostAudioProcessor::new(OPUS_SAMPLE_RATE as u32, 2, true, bitrate_kbps);
        let sequence = AtomicU32::new(1);
        client.start_stream()?;
        let _ = ready.send(Ok(()));
        let mut next_check = std::time::Instant::now();
        while !stop.load(Ordering::Relaxed) {
            if !include && pid != std::process::id() && std::time::Instant::now() >= next_check {
                if discord_root_pid() != Ok(pid) {
                    warn!("Discord process changed; stopped filtered audio until hosting restarts");
                    break;
                }
                next_check = std::time::Instant::now() + std::time::Duration::from_millis(100);
            }
            while !stop.load(Ordering::Relaxed) && capture.get_next_packet_size()?.unwrap_or(0) > 0
            {
                capture.read_from_device_to_deque(&mut bytes)?;
                let pcm = bytes_to_f32_vec(bytes.make_contiguous());
                processor.push_and_emit(&pcm, &sequence, tx);
                bytes.clear();
            }
            let _ = event.wait_for_event(25);
        }
        client.stop_stream()
    })();
    wasapi::deinitialize();
    result.map_err(|err| format!("Filtered Opus audio unavailable for PID {pid}: {err}"))
}

fn bytes_to_f32_vec(bytes: &[u8]) -> Vec<f32> {
    let (chunks, _) = bytes.as_chunks::<4>();
    chunks
        .iter()
        .map(|chunk| f32::from_le_bytes(*chunk))
        .collect()
}

